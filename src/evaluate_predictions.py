"""CLI for evaluating stored forecasts against realised prices."""

from __future__ import annotations

import argparse
from pathlib import Path

from .evaluation import evaluate_predictions


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate forecast JSON against realised closes.")
    parser.add_argument("--predictions", type=Path, required=True, help="Forecast JSON generated by run_inference.")
    parser.add_argument("--metrics-out", type=Path, required=True, help="Destination JSON for evaluation metrics.")
    parser.add_argument(
        "--price-history",
        type=Path,
        help="Optional CSV for realised closes to avoid repeated downloads.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    results = evaluate_predictions(
        args.predictions, metrics_output=args.metrics_out, price_history_path=args.price_history
    )
    metrics = results["metrics"]
    print(
        f"{results['ticker']} evaluation ({metrics['count']} points) -> "
        f"MAE {metrics['mae']:.4f}, RMSE {metrics['rmse']:.4f}, MAPE {metrics['mape']:.2f}%"
    )


if __name__ == "__main__":
    main()
